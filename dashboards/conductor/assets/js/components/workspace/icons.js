const SVGNS = 'http://www.w3.org/2000/svg';
let sprite = null;
export function ensureWorkspaceIcons() {
  if (typeof document === 'undefined') return;
  const missing = Object.keys(SYMBOLS).filter((name) => !document.getElementById(`i-${name}`));
  if (!missing.length) return;
  if (!sprite) {
    sprite = document.createElementNS(SVGNS, 'svg');
    sprite.setAttribute('width', '0');
    sprite.setAttribute('height', '0');
    sprite.setAttribute('aria-hidden', 'true');
    sprite.setAttribute('focusable', 'false');
    sprite.style.position = 'absolute';
    document.body.prepend(sprite);
  }
  for (const name of missing) {
    const sym = document.createElementNS(SVGNS, 'symbol');
    sym.id = `i-${name}`;
    sym.setAttribute('viewBox', '0 0 24 24');
    sym.innerHTML = SYMBOLS[name]; // constant markup defined above; never data
    sprite.append(sym);
  }
}
